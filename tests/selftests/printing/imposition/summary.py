def run(ctx) -> None:
    from pathlib import Path
    from tests.selftests._context import make_pdf, ok, pump
    import shutil
    import tempfile

    st = SimpleNamespace(ctx=ctx)
    tmp = Path(tempfile.mkdtemp(prefix="guji_imposition_"))
    page = None
    st.page = page
    st.tmp = tmp

    try:
        for part, _title in PARTS:
            part.run(st)
    finally:
        if st.page is not None:
            try:
                st.page._imposition_timer.stop()
            except RuntimeError:
                pass
            # ⚠️ 用 shutdown_all_workers 而不是 shutdown_workers：本页是**独立**
            # 构造的（不挂在 st.ctx.w 上），它自己的 PDF 预览等子控件各有线程宿主；
            # 只收页面自己的会让那些线程活到解释器退出（同进程后续模块还在跑）。
            st.page.shutdown_all_workers()
            st.page.hide()
            st.page.deleteLater()
            pump(st.ctx.app, times=4)
        shutil.rmtree(st.tmp, ignore_errors=True)

