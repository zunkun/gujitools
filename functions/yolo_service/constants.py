# -*- coding: utf-8 -*-
"""常驻 YOLO 服务的常量：发现文件、超时、日志上限与进程优先级。"""

#: 服务发现文件（按用户临时目录）。⚠️ 文件名带**指纹**：
#: 开发版与正式版可能在同一台机器上同时跑（单例按构建区分），两者的权重路径
#: 不同 → 指纹不同 → 各用各的发现文件，互不覆盖。否则两边会互相改写同一个
#: 文件，另一方读到的端口不是自己的服务，就被迫重拉一个新服务、无限往复。
SERVICE_FILE_PREFIX = "guji-yolo-service-"

#: 空闲多久没人用就退出（秒）；**None＝常驻不退出**（2026-10-13 用户口径：
#: "yolo 加载到内存全局，会只加载一次，不要释放"——模型约 350MB 一直驻留，
#: 每次检测、每个会话都零加载等待）。环境变量 `GUJI_YOLO_TTL` 可显式给一个
#: 有限值（下限 5 秒）——自测与排障用它验证自退机制；不给就是常驻。
DEFAULT_TTL_SECONDS: float | None = None

#: 建连与握手超时（秒）
CONNECT_TIMEOUT = 3.0
#: 单次检测的等待上限（秒）。首张图要等 torch 导入 + 载模型（约 5.5s），
#: 之后每张一两百毫秒；给足余量避免大图/慢机器上误判超时。
DETECT_TIMEOUT = 300.0
#: 拉起服务后，最多等它多久可用（秒）
SPAWN_WAIT = 25.0

#: 服务日志体积上限：超过就在**服务启动时**换一份新的（不按行轮转，简单可靠）
LOG_MAX_BYTES = 2 * 1024 * 1024

# ---------------------------------------------------------------- 进程优先级
#: Windows 优先级类别：BELOW_NORMAL（空闲/预热时让出 CPU）与 NORMAL（真检测）
_BELOW_NORMAL_PRIORITY_CLASS = 0x00004000
_NORMAL_PRIORITY_CLASS = 0x00000020
